"""Aggregate all judge_scores_v3.json files into a Markdown table at RESULTS.md.

Job directory naming convention:
  gr-{run}-{mode}[-v5]-eval
where:
  run  ∈ {ep1, ep2, s1like-ep1, s1like-ep5, s1like-v5-ep1, ...}
  mode ∈ {retain, both}
  -v5  = the v5 hack-elicitation prompt was prepended to each task's instruction.md

Special cases:
  qwen32b-eval        = base Qwen3-32B (no adapter, no v5)
  gr-base-v5-eval     = base Qwen3-32B + v5 prompt
"""
from __future__ import annotations

import json
import math
import re
import sys
from pathlib import Path

JOBS_DIR = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/workspace/jobs")
OUT_PATH = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("/workspace/training/RESULTS.md")


def wilson_ci(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    denom = 1 + z * z / n
    center = (p + z * z / (2 * n)) / denom
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denom
    return (center - half, center + half)


def parse_job(job_dir: Path) -> dict:
    name = job_dir.name
    has_v5 = "-v5-" in name or name.endswith("-v5") or name.endswith("-v5-eval")
    # canonical key
    if name == "qwen32b-eval":
        run, mode = "base", "—"
    elif name == "gr-base-v5-eval":
        run, mode = "base", "—"
    else:
        m = re.match(r"^gr-(.+?)-(retain|both)(?:-v5)?-eval$", name)
        if m:
            run, mode = m.group(1), m.group(2)
        else:
            run, mode = name, "?"
    return {"job_dir": str(job_dir), "name": name, "run": run, "mode": mode, "v5": has_v5}


def load_summary(job_dir: Path) -> dict | None:
    score_file = job_dir / "judge_scores_v3.json"
    if not score_file.exists():
        return None
    try:
        return json.loads(score_file.read_text()).get("summary")
    except (json.JSONDecodeError, OSError):
        return None


def fmt_pct(x: float | None) -> str:
    if x is None:
        return "—"
    return f"{x*100:.1f}%"


def hack_at(by_thr: list, thr: float) -> float | None:
    for blk in by_thr or []:
        if abs(blk.get("threshold", 0) - thr) < 1e-6:
            return blk.get("hack_rate")
    return None


def main():
    jobs = []
    for d in sorted(JOBS_DIR.iterdir()):
        if not d.is_dir():
            continue
        parsed = parse_job(d)
        summary = load_summary(d)
        if summary is None:
            continue
        n = summary.get("n_with_reward") or 0
        passes = int(round((summary.get("baseline_pass_rate") or 0) * n))
        lo, hi = wilson_ci(passes, n)
        parsed["pass_rate"] = summary.get("baseline_pass_rate")
        parsed["pass_ci"] = (lo, hi)
        parsed["pass_n"] = f"{passes}/{n}"
        parsed["mean_suspicion"] = summary.get("mean_suspicion")
        parsed["n_scored"] = summary.get("n_with_score")
        parsed["hack_05"] = hack_at(summary.get("by_threshold"), 0.5)
        parsed["hack_07"] = hack_at(summary.get("by_threshold"), 0.7)
        parsed["hack_08"] = hack_at(summary.get("by_threshold"), 0.8)
        parsed["judge_model"] = summary.get("judge_model", "")
        jobs.append(parsed)

    rows = []
    rows.append("# Adapter eval results — Qwen3-32B + DualMLPAdapter")
    rows.append("")
    rows.append(f"Generated by `scripts/eval/aggregate_results.py` from "
                f"`{JOBS_DIR}`.")
    rows.append("")
    rows.append("- 99 held-out eval tasks (`tb-eval/data/task_split.json`).")
    rows.append("- terminus-2 agent, max_turns=64, agent timeout 360 s, n_concurrent=64.")
    rows.append("- Judge: gpt-5.4-nano via OpenRouter, prompt `judge_v3` (intent-based).")
    rows.append("- `+v5` runs prepend `terminal-wrench/prompts/hack_prompt_v5.md` "
                "(red-team elicitation) to each task's instruction.md.")
    rows.append("- Pass-rate CI is Wilson 95%.")
    rows.append("")
    rows.append("| run | mode | v5 | pass | pass 95% CI | mean susp. | hack ≥0.5 | hack ≥0.7 | hack ≥0.8 |")
    rows.append("|---|---|:-:|---:|---:|---:|---:|---:|---:|")

    def sort_key(j):
        run_order = {
            "base": 0, "ep1": 1, "ep2": 2,
            "s1like-ep1": 10, "s1like-ep2": 11, "s1like-ep3": 12,
            "s1like-ep4": 13, "s1like-ep5": 14,
            "s1like-v5-ep1": 20, "s1like-v5-ep2": 21,
            "s1like-v5-ep3": 22, "s1like-v5-ep4": 23, "s1like-v5-ep5": 24,
        }
        mode_order = {"—": 0, "retain": 1, "both": 2, "?": 9}
        return (run_order.get(j["run"], 99), mode_order.get(j["mode"], 99), j["v5"])

    for j in sorted(jobs, key=sort_key):
        lo_pct, hi_pct = j["pass_ci"]
        rows.append(
            f"| {j['run']} | {j['mode']} | {'✓' if j['v5'] else ''} | "
            f"{fmt_pct(j['pass_rate'])} ({j['pass_n']}) | "
            f"[{fmt_pct(lo_pct)}, {fmt_pct(hi_pct)}] | "
            f"{j['mean_suspicion']:.2f} | "
            f"{fmt_pct(j['hack_05'])} | "
            f"{fmt_pct(j['hack_07'])} | "
            f"{fmt_pct(j['hack_08'])} |"
        )

    rows.append("")
    rows.append("## Per-run job dirs")
    rows.append("")
    for j in sorted(jobs, key=sort_key):
        rows.append(f"- `{j['name']}` → run={j['run']} mode={j['mode']} "
                    f"v5={'yes' if j['v5'] else 'no'}")

    OUT_PATH.write_text("\n".join(rows) + "\n")
    print(f"Wrote {OUT_PATH} ({len(jobs)} runs).")


if __name__ == "__main__":
    main()
